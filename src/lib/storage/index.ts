import 'server-only'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { getEnv } from '@/config/env'
import { S3Storage } from './s3'

/**
 * Private file storage. Nothing here is ever served from `public/`: files leave only
 * through route handlers that check permission (or a signed, expiring link).
 */
export interface StorageDriver {
  put(key: string, bytes: Uint8Array): Promise<void>
  /** Null when the file does not exist (e.g. purged, or seed metadata only). */
  get(key: string): Promise<Uint8Array | null>
  delete(key: string): Promise<void>
}

/** Keys are generated by the app; this guards against path traversal all the same. */
const KEY_PATTERN = /^[a-z0-9-]+(\/[a-zA-Z0-9-]+)+$/

export function assertStorageKey(key: string): void {
  if (!KEY_PATTERN.test(key) || key.length > 200) throw new Error(`Invalid storage key: ${key}`)
}

export class LocalStorage implements StorageDriver {
  constructor(private readonly root: string) {}

  private file(key: string): string {
    assertStorageKey(key)
    const full = path.resolve(this.root, ...key.split('/'))
    if (!full.startsWith(path.resolve(this.root) + path.sep)) {
      throw new Error(`Invalid storage key: ${key}`)
    }
    return full
  }

  async put(key: string, bytes: Uint8Array): Promise<void> {
    const file = this.file(key)
    await mkdir(path.dirname(file), { recursive: true })
    // `wx` refuses to overwrite: every key is new.
    await writeFile(file, bytes, { flag: 'wx' })
  }

  async get(key: string): Promise<Uint8Array | null> {
    try {
      return new Uint8Array(await readFile(this.file(key)))
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null
      throw error
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.file(key), { force: true })
  }
}

let driver: StorageDriver | undefined

export function getStorage(): StorageDriver {
  if (driver) return driver
  const env = getEnv()
  if (env.STORAGE_DRIVER === 's3') {
    // Validated at boot: every S3 setting is present when the driver is s3.
    driver = new S3Storage({
      endpoint: env.S3_ENDPOINT!,
      bucket: env.S3_BUCKET!,
      region: env.S3_REGION,
      accessKeyId: env.S3_ACCESS_KEY_ID!,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY!,
      pathStyle: env.S3_FORCE_PATH_STYLE,
    })
    return driver
  }
  driver = new LocalStorage(path.resolve(env.STORAGE_LOCAL_DIR))
  return driver
}

/** Tests swap in a temporary directory. */
export function setStorageForTests(next: StorageDriver | undefined): void {
  driver = next
}
